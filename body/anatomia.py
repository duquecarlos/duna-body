"""Body-view data (BODY-CUERPO-VISTA-1): mock round 2's one body view per main screen, read once
from the static anatomy assets this slice copies in (body/static/anatomia/ -- the final art the
orchestrator staged, Google AI Studio / Gemini image model, generated by Carlos 2026-11-09 on his
own account; Google's generative-AI terms need checking before a hosted Duna product uses it,
fallback Servier Medical Art CC BY 4.0), plus the fixed map from a training exercise's categoria to
the glow groups it lights (ruling 2) -- data, never hand-placed per template, so a new screen or a
new category is a change here, not in three templates.
"""
from __future__ import annotations

import json
from pathlib import Path

from .i18n import T

_DIR = Path(__file__).parent / "static" / "anatomia"
_ANCLAJES = json.loads((_DIR / "anclajes.json").read_text(encoding="utf-8"))

VISTAS_POR_PANTALLA: dict[str, list[dict]] = _ANCLAJES["vistas_por_pantalla"]
BRILLOS: dict[str, dict[str, list[list[float]]]] = _ANCLAJES["brillos"]

# Every front-posed image shares one framing (BRILLOS["frente"]); every back-posed one shares the
# other (BRILLOS["espalda"]) -- anclajes.json's own "_nota". Profile and the close-up vías aéreas
# view carry no glow pose here -- neither screen in this slice uses them.
IMAGEN_POSE: dict[str, str] = {
    "frente": "frente", "corazon": "frente", "nervios": "frente", "cerebro": "frente",
    "pulmones": "frente", "musculos": "frente", "esqueleto": "frente",
    "espalda": "espalda", "espalda-musculos": "espalda", "espalda-columna": "espalda",
}

# Ruling 2: a training exercise's categoria -> the glow groups it lights (BRILLOS' own group
# keys -- a leg category lights front quads AND the back's own glutes/hamstrings, same session).
# A categoria with no entry here lights nothing -- never guessed. registrar_entreno's own
# `categoria` parameter is free text (body/agente/herramientas.py _PARAM_REGISTRAR_ENTRENO, no
# enum); these are the Spanish muscle-group words it's seen in practice (tests/test_entreno_sets.py,
# tests/test_agente_propuestas.py), singular and plural.
CATEGORIA_GRUPOS: dict[str, frozenset[str]] = {
    "pierna": frozenset({"cuadriceps", "gluteos", "isquios"}),
    "piernas": frozenset({"cuadriceps", "gluteos", "isquios"}),
    "espalda": frozenset({"dorsales", "espalda_alta", "deltoides_post"}),
    "pecho": frozenset({"pecho"}),
    "hombro": frozenset({"hombros"}),
    "hombros": frozenset({"hombros"}),
    "brazo": frozenset({"biceps"}),
    "brazos": frozenset({"biceps"}),
    "core": frozenset({"abdomen"}),
}

# Stable display order for a caption's {grupos} list -- front groups before back groups, never
# set-iteration order (which Python does not guarantee across runs for a frozenset of strings).
GRUPOS_ORDEN: list[str] = ["pecho", "hombros", "biceps", "abdomen", "dorsales", "espalda_alta",
                           "deltoides_post", "cuadriceps", "gluteos", "isquios"]

# Which of BRILLOS' own groups each (pantalla, vista id) may ever light. BRILLOS is keyed by POSE
# (frente/espalda), not by view -- Hoy's "corazon" view shares its coordinates with "musculos" (both
# front-posed), so without this a leg category would also glow on the heart view. Each view gets
# only the groups its own screen reserves for it; "corazon"/"cerebro" are reserved to Tendencias/
# Turnos' own static glow and never lit by a training category (CATEGORIA_GRUPOS never produces
# them), and a view with no entry here never lights at all.
VISTA_GRUPOS: dict[tuple[str, str], frozenset[str]] = {
    ("hoy", "musculos"): frozenset({"pecho", "hombros", "biceps", "cuadriceps", "abdomen"}),
    ("hoy", "espalda"): frozenset({"dorsales", "espalda_alta", "deltoides_post", "gluteos", "isquios"}),
    ("hoy", "corazon"): frozenset({"corazon"}),
    ("tendencias", "corazon"): frozenset({"corazon"}),
    ("turnos", "cerebro"): frozenset({"cerebro"}),
}


def grupos_de_categorias(categorias) -> frozenset[str]:
    """Union of glow groups for a session's own list of categoria strings -- an unrecognised,
    empty or missing categoria contributes nothing."""
    out: set[str] = set()
    for c in categorias:
        if c:
            out |= CATEGORIA_GRUPOS.get(c.strip().lower(), frozenset())
    return frozenset(out)


def grupos_ordenados(grupos) -> list[str]:
    return [g for g in GRUPOS_ORDEN if g in grupos]


def _alt(t: T, pantalla: str, vista_id: str) -> str:
    """Three literal t() calls, the same reason body/rutas/hoy.py's own _momento_checkin_txt
    gives: tests/test_i18n_paridad.py's dynamic-prefix guard needs each prefix typed out, not
    built from a runtime `pantalla`."""
    if pantalla == "hoy":
        return t("cuerpo.alt.hoy." + vista_id)
    if pantalla == "tendencias":
        return t("cuerpo.alt.tendencias." + vista_id)
    return t("cuerpo.alt.turnos." + vista_id)


def contexto(t: T, pantalla: str, grupos_lit: frozenset[str] = frozenset()) -> list[dict]:
    """This screen's own views (anclajes.json's order), each with its glow ellipses for
    `grupos_lit` -- filtered to whichever pose (front or back) that view's own image actually
    carries them for, so a leg category lights cuádriceps on a front view and glúteos +
    isquiotibiales on a back view of the SAME session, never both on either."""
    out = []
    for v in VISTAS_POR_PANTALLA[pantalla]:
        imagen = v["imagen"]
        pose = IMAGEN_POSE.get(imagen)
        disponibles = BRILLOS.get(pose, {}) if pose else {}
        permitidos = VISTA_GRUPOS.get((pantalla, v["id"]), frozenset())
        glow = [elipse for g in (grupos_lit & permitidos) for elipse in disponibles.get(g, [])]
        out.append({"id": v["id"], "imagen": imagen, "glow": glow,
                    "label": t("cuerpo.vista." + v["id"]), "alt": _alt(t, pantalla, v["id"])})
    return out
